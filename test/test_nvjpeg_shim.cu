static int counting_device_malloc(void **ptr, size_t size) {
  ++device_mallocs;
  return static_cast<int>(cudaMalloc(ptr, size));
}

static int counting_device_free(void *ptr) {
  return static_cast<int>(cudaFree(ptr));
}

static int counting_pinned_malloc(void **ptr, size_t size, unsigned int flags) {
  ++pinned_mallocs;
  return static_cast<int>(cudaHostAlloc(ptr, size, flags));
}

static int counting_pinned_free(void *ptr) {
  return static_cast<int>(cudaFreeHost(ptr));
}

// A library on another machine cannot call these, so through the shim the
// server's library allocates with its defaults and the counters stay at zero;
// natively they count. Either way the handle decodes.
static int test_allocators() {
  nvjpegDevAllocator_t device_allocator = {counting_device_malloc,
                                           counting_device_free};
  nvjpegPinnedAllocator_t pinned_allocator = {counting_pinned_malloc,
                                              counting_pinned_free};
  nvjpegHandle_t handle = nullptr;
  CHECK_NVJPEG(nvjpegCreateEx(NVJPEG_BACKEND_DEFAULT, &device_allocator,
                              &pinned_allocator, NVJPEG_FLAGS_DEFAULT,
                              &handle));
  CHECK_NVJPEG(nvjpegSetDeviceMemoryPadding(1 << 16, handle));
  CHECK_NVJPEG(nvjpegSetPinnedMemoryPadding(1 << 12, handle));
  size_t padding = 0;
  CHECK_NVJPEG(nvjpegGetDeviceMemoryPadding(&padding, handle));
  EXPECT(padding == 1 << 16);
  CHECK_NVJPEG(nvjpegGetPinnedMemoryPadding(&padding, handle));
  EXPECT(padding == 1 << 12);
  if (test_single_call(handle)) {
    return 1;
  }
  nvjpegBufferDevice_t device = nullptr;
  CHECK_NVJPEG(nvjpegBufferDeviceCreate(handle, &device_allocator, &device));
  CHECK_NVJPEG(nvjpegBufferDeviceDestroy(device));
  printf("  allocator wrappers called: device %d, pinned %d\n", device_mallocs,
         pinned_mallocs);
  CHECK_NVJPEG(nvjpegDestroy(handle));
  return 0;
}

static int test_multi_device() {
  int count = 0;
  CHECK_CUDA(cudaGetDeviceCount(&count));
  if (count < 2) {
    printf("  one device; skipping the per-device decode\n");
    return 0;
  }
  for (int device = 0; device < 2; ++device) {
    CHECK_CUDA(cudaSetDevice(device));
    nvjpegHandle_t handle = nullptr;
    CHECK_NVJPEG(nvjpegCreateSimple(&handle));
    if (test_single_call(handle) ||
        decode_decoupled(handle, NVJPEG_BACKEND_DEFAULT, 0, true)) {
      fprintf(stderr, "on device %d\n", device);
      return 1;
    }
    CHECK_NVJPEG(nvjpegDestroy(handle));
  }
  CHECK_CUDA(cudaSetDevice(0));
  return 0;
}

int main() {
  int major = -1, minor = -1, patch = -1;
  CHECK_NVJPEG(nvjpegGetProperty(MAJOR_VERSION, &major));
  CHECK_NVJPEG(nvjpegGetProperty(MINOR_VERSION, &minor));
  CHECK_NVJPEG(nvjpegGetProperty(PATCH_LEVEL, &patch));
  EXPECT(major == NVJPEG_VER_MAJOR);
  int cuda_major = -1;
  CHECK_NVJPEG(nvjpegGetCudartProperty(MAJOR_VERSION, &cuda_major));
  EXPECT(cuda_major > 0);

  nvjpegHandle_t handle = nullptr;
  CHECK_NVJPEG(nvjpegCreateSimple(&handle));
  if (test_image_info(handle) || test_single_call(handle) ||
      test_decoupled(handle) || test_batched(handle) || test_encode(handle) ||
      test_allocators() || test_multi_device()) {
    return 1;
  }
  CHECK_NVJPEG(nvjpegDestroy(handle));
  printf("nvjpeg shim: all checks passed (nvJPEG %d.%d.%d)\n", major, minor,
         patch);
  return 0;
}
