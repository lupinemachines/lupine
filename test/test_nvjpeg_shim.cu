struct embedded_image {
  const unsigned char *data;
  size_t length;
  unsigned width;
  unsigned height;
  int blue;
};

static const embedded_image kImageA = {kGradient64x48, sizeof(kGradient64x48),
                                       64, 48, 37};
static const embedded_image kImageB = {kGradient40x24, sizeof(kGradient40x24),
                                       40, 24, 111};

// Lossy 4:2:0 compression of a smooth gradient stays within a few levels on
// average; a misplaced or unwritten plane is off by tens.
static const double kMeanTolerance = 6.0;

static int expected(unsigned channel, unsigned x, unsigned y, unsigned width,
                    unsigned height, int blue) {
  switch (channel) {
  case 0:
    return static_cast<int>(x * 255 / (width - 1));
  case 1:
    return static_cast<int>(y * 255 / (height - 1));
  default:
    return static_cast<int>(blue + x + y);
  }
}

struct device_image {
  nvjpegImage_t image{};
  unsigned width = 0;
  unsigned height = 0;
  int blue = 0;
  bool interleaved = true;
};

static int allocate(device_image *out, const embedded_image &source,
                    bool interleaved) {
  const unsigned width = source.width, height = source.height;
  out->image = nvjpegImage_t{};
  out->width = width;
  out->height = height;
  out->blue = source.blue;
  out->interleaved = interleaved;
  if (interleaved) {
    CHECK_CUDA(cudaMalloc(&out->image.channel[0], width * height * 3));
    out->image.pitch[0] = width * 3;
    return 0;
  }
  for (int c = 0; c < 3; ++c) {
    CHECK_CUDA(cudaMalloc(&out->image.channel[c], width * height));
    out->image.pitch[c] = width;
  }
  return 0;
}

static void release(device_image *image) {
  for (int c = 0; c < 3; ++c) {
    cudaFree(image->image.channel[c]);
    image->image.channel[c] = nullptr;
  }
}

// Copies the image back and compares it with the gradient, returning nonzero
// with a message when the mean channel error is past tolerance.
static int check_pixels(const char *what, const device_image &image) {
  const unsigned w = image.width, h = image.height;
  std::vector<unsigned char> planes[3];
  if (image.interleaved) {
    planes[0].resize(w * h * 3);
    CHECK_CUDA(cudaMemcpy(planes[0].data(), image.image.channel[0],
                          planes[0].size(), cudaMemcpyDeviceToHost));
  } else {
    for (int c = 0; c < 3; ++c) {
      planes[c].resize(w * h);
      CHECK_CUDA(cudaMemcpy(planes[c].data(), image.image.channel[c],
                            planes[c].size(), cudaMemcpyDeviceToHost));
    }
  }
  double error = 0.0;
  for (unsigned y = 0; y < h; ++y) {
    for (unsigned x = 0; x < w; ++x) {
      for (unsigned c = 0; c < 3; ++c) {
        const int got = image.interleaved ? planes[0][(y * w + x) * 3 + c]
                                          : planes[c][y * w + x];
        error += std::abs(got - expected(c, x, y, w, h, image.blue));
      }
    }
  }
  const double mean = error / (w * h * 3);
  if (mean > kMeanTolerance) {
    fprintf(stderr, "%s: mean channel error %.2f exceeds %.2f\n", what, mean,
            kMeanTolerance);
    return 1;
  }
  return 0;
}

static int test_image_info(nvjpegHandle_t handle) {
  int components = 0;
  nvjpegChromaSubsampling_t subsampling = NVJPEG_CSS_UNKNOWN;
  int widths[NVJPEG_MAX_COMPONENT] = {};
  int heights[NVJPEG_MAX_COMPONENT] = {};
  CHECK_NVJPEG(nvjpegGetImageInfo(handle, kImageA.data, kImageA.length,
                                  &components, &subsampling, widths, heights));
  EXPECT(components == 3);
  EXPECT(subsampling == NVJPEG_CSS_420);
  EXPECT(widths[0] == 64 && heights[0] == 48);
  EXPECT(widths[1] == 32 && heights[1] == 24);
  EXPECT(widths[2] == 32 && heights[2] == 24);

  const unsigned char garbage[64] = {0xff, 0xd8, 0x00};
  EXPECT(nvjpegGetImageInfo(handle, garbage, sizeof(garbage), &components,
                            &subsampling, widths, heights) !=
         NVJPEG_STATUS_SUCCESS);
  return 0;
}

static int test_single_call(nvjpegHandle_t handle) {
  nvjpegJpegState_t state = nullptr;
  CHECK_NVJPEG(nvjpegJpegStateCreate(handle, &state));
  for (bool interleaved : {true, false}) {
    for (const embedded_image *source : {&kImageA, &kImageB}) {
      device_image out;
      if (allocate(&out, *source, interleaved)) {
        return 1;
      }
      CHECK_NVJPEG(nvjpegDecode(
          handle, state, source->data, source->length,
          interleaved ? NVJPEG_OUTPUT_RGBI : NVJPEG_OUTPUT_RGB, &out.image,
          nullptr));
      CHECK_CUDA(cudaDeviceSynchronize());
      if (check_pixels(interleaved ? "nvjpegDecode RGBI" : "nvjpegDecode RGB",
                       out)) {
        return 1;
      }
      release(&out);
    }
  }
  CHECK_NVJPEG(nvjpegJpegStateDestroy(state));
  return 0;
}

// Host, transfer and device phases against a bitstream object that
// references the bytes it parsed. A same-sized bitstream sent in between would
// land where a server copy of the parsed bytes was freed.
static int decode_decoupled(nvjpegHandle_t handle, nvjpegBackend_t backend,
                            int save_stream, bool interleaved) {
  nvjpegJpegDecoder_t decoder = nullptr;
  nvjpegStatus_t status = nvjpegDecoderCreate(handle, backend, &decoder);
  if (status == NVJPEG_STATUS_ARCH_MISMATCH ||
      status == NVJPEG_STATUS_IMPLEMENTATION_NOT_SUPPORTED) {
    printf("  backend %d not available here (%d)\n", static_cast<int>(backend),
           static_cast<int>(status));
    return 0;
  }
  CHECK_NVJPEG(status);
  nvjpegJpegState_t state = nullptr;
  nvjpegJpegStream_t stream = nullptr;
  nvjpegDecodeParams_t params = nullptr;
  nvjpegBufferPinned_t pinned = nullptr;
  nvjpegBufferDevice_t device = nullptr;
  CHECK_NVJPEG(nvjpegDecoderStateCreate(handle, decoder, &state));
  CHECK_NVJPEG(nvjpegJpegStreamCreate(handle, &stream));
  CHECK_NVJPEG(nvjpegDecodeParamsCreate(handle, &params));
  CHECK_NVJPEG(nvjpegBufferPinnedCreate(handle, nullptr, &pinned));
  CHECK_NVJPEG(nvjpegBufferDeviceCreate(handle, nullptr, &device));
  CHECK_NVJPEG(nvjpegStateAttachPinnedBuffer(state, pinned));
  CHECK_NVJPEG(nvjpegStateAttachDeviceBuffer(state, device));
  CHECK_NVJPEG(nvjpegDecodeParamsSetOutputFormat(
      params, interleaved ? NVJPEG_OUTPUT_RGBI : NVJPEG_OUTPUT_RGB));

  std::vector<unsigned char> bytes(kImageA.data,
                                   kImageA.data + kImageA.length);
  CHECK_NVJPEG(nvjpegJpegStreamParseHeader(handle, bytes.data(), bytes.size(),
                                           stream));
  unsigned width = 0, height = 0, components = 0;
  CHECK_NVJPEG(nvjpegJpegStreamGetFrameDimensions(stream, &width, &height));
  CHECK_NVJPEG(nvjpegJpegStreamGetComponentsNum(stream, &components));
  EXPECT(width == 64 && height == 48 && components == 3);
  unsigned chroma_width = 0, chroma_height = 0;
  CHECK_NVJPEG(nvjpegJpegStreamGetComponentDimensions(stream, 1, &chroma_width,
                                                      &chroma_height));
  EXPECT(chroma_width == 32 && chroma_height == 24);
  nvjpegChromaSubsampling_t subsampling = NVJPEG_CSS_UNKNOWN;
  CHECK_NVJPEG(nvjpegJpegStreamGetChromaSubsampling(stream, &subsampling));
  EXPECT(subsampling == NVJPEG_CSS_420);
  nvjpegJpegEncoding_t encoding = NVJPEG_ENCODING_UNKNOWN;
  CHECK_NVJPEG(nvjpegJpegStreamGetJpegEncoding(stream, &encoding));
  EXPECT(encoding == NVJPEG_ENCODING_BASELINE_DCT);

  CHECK_NVJPEG(nvjpegJpegStreamParse(handle, bytes.data(), bytes.size(), 0,
                                     save_stream, stream));
  int supported = -1;
  CHECK_NVJPEG(nvjpegDecoderJpegSupported(decoder, stream, params, &supported));
  EXPECT(supported == 0);
  std::vector<unsigned char> filler(bytes.size(), 0x5a);
  int filler_components = 0;
  nvjpegChromaSubsampling_t filler_subsampling = NVJPEG_CSS_UNKNOWN;
  int filler_widths[NVJPEG_MAX_COMPONENT] = {};
  int filler_heights[NVJPEG_MAX_COMPONENT] = {};
  EXPECT(nvjpegGetImageInfo(handle, filler.data(), filler.size(),
                            &filler_components, &filler_subsampling,
                            filler_widths, filler_heights) !=
         NVJPEG_STATUS_SUCCESS);

  device_image out;
  if (allocate(&out, kImageA, interleaved)) {
    return 1;
  }
  CHECK_NVJPEG(nvjpegDecodeJpegHost(handle, decoder, state, params, stream));
  CHECK_NVJPEG(
      nvjpegDecodeJpegTransferToDevice(handle, decoder, state, stream, nullptr));
  CHECK_NVJPEG(
      nvjpegDecodeJpegDevice(handle, decoder, state, &out.image, nullptr));
  CHECK_CUDA(cudaDeviceSynchronize());
  char what[96];
  snprintf(what, sizeof(what), "decoupled backend %d save_stream %d %s",
           static_cast<int>(backend), save_stream,
           interleaved ? "RGBI" : "RGB");
  if (check_pixels(what, out)) {
    return 1;
  }

  // The staging buffers the phases used were sized by them; the addresses
  // belong to whichever process ran the library.
  size_t pinned_size = 0, device_size = 0;
  void *pinned_ptr = nullptr, *device_ptr = nullptr;
  CHECK_NVJPEG(nvjpegBufferPinnedRetrieve(pinned, &pinned_size, &pinned_ptr));
  CHECK_NVJPEG(nvjpegBufferDeviceRetrieve(device, &device_size, &device_ptr));
  EXPECT(device_size > 0 && device_ptr != nullptr);

  // One call through the same objects, from a fresh parse.
  CHECK_NVJPEG(nvjpegJpegStreamParse(handle, kImageB.data, kImageB.length, 0, 0,
                                     stream));
  release(&out);
  if (allocate(&out, kImageB, interleaved)) {
    return 1;
  }
  CHECK_NVJPEG(nvjpegDecodeJpeg(handle, decoder, state, stream, &out.image,
                                params, nullptr));
  CHECK_CUDA(cudaDeviceSynchronize());
  snprintf(what, sizeof(what), "nvjpegDecodeJpeg backend %d %s",
           static_cast<int>(backend), interleaved ? "RGBI" : "RGB");
  if (check_pixels(what, out)) {
    return 1;
  }
  release(&out);

  CHECK_NVJPEG(nvjpegJpegStateDestroy(state));
  CHECK_NVJPEG(nvjpegBufferPinnedDestroy(pinned));
  CHECK_NVJPEG(nvjpegBufferDeviceDestroy(device));
  CHECK_NVJPEG(nvjpegDecodeParamsDestroy(params));
  CHECK_NVJPEG(nvjpegJpegStreamDestroy(stream));
  CHECK_NVJPEG(nvjpegDecoderDestroy(decoder));
  return 0;
}

static int test_decoupled(nvjpegHandle_t handle) {
  for (nvjpegBackend_t backend :
       {NVJPEG_BACKEND_DEFAULT, NVJPEG_BACKEND_HYBRID,
        NVJPEG_BACKEND_GPU_HYBRID}) {
    for (int save_stream : {0, 1}) {
      for (bool interleaved : {true, false}) {
        if (decode_decoupled(handle, backend, save_stream, interleaved)) {
          return 1;
        }
      }
    }
  }
  return 0;
}

static int test_batched(nvjpegHandle_t handle) {
  nvjpegJpegState_t state = nullptr;
  CHECK_NVJPEG(nvjpegJpegStateCreate(handle, &state));
  CHECK_NVJPEG(
      nvjpegDecodeBatchedInitialize(handle, state, 2, 1, NVJPEG_OUTPUT_RGBI));
  const embedded_image *sources[2] = {&kImageA, &kImageB};
  const unsigned char *data[2] = {kImageA.data, kImageB.data};
  size_t lengths[2] = {kImageA.length, kImageB.length};
  device_image outs[2];
  nvjpegImage_t destinations[2];
  for (int i = 0; i < 2; ++i) {
    if (allocate(&outs[i], *sources[i], true)) {
      return 1;
    }
    destinations[i] = outs[i].image;
  }
  CHECK_NVJPEG(nvjpegDecodeBatched(handle, state, data, lengths, destinations,
                                   nullptr));
  CHECK_CUDA(cudaDeviceSynchronize());
  for (int i = 0; i < 2; ++i) {
    if (check_pixels(i == 0 ? "batched image 0" : "batched image 1",
                     outs[i])) {
      return 1;
    }
  }

  // The parameterized form is the hardware backend's; the others refuse it
  // with a status rather than decoding.
  nvjpegDecodeParams_t params[2] = {};
  for (int i = 0; i < 2; ++i) {
    CHECK_NVJPEG(nvjpegDecodeParamsCreate(handle, &params[i]));
    CHECK_NVJPEG(nvjpegDecodeParamsSetOutputFormat(params[i], NVJPEG_OUTPUT_RGBI));
  }
  const nvjpegStatus_t ex_status = nvjpegDecodeBatchedEx(
      handle, state, data, lengths, destinations, params, nullptr);
  CHECK_CUDA(cudaDeviceSynchronize());
  printf("  nvjpegDecodeBatchedEx on the default backend: %d\n",
         static_cast<int>(ex_status));
  if (ex_status == NVJPEG_STATUS_SUCCESS) {
    for (int i = 0; i < 2; ++i) {
      if (check_pixels("nvjpegDecodeBatchedEx", outs[i])) {
        return 1;
      }
    }
  }
  for (int i = 0; i < 2; ++i) {
    CHECK_NVJPEG(nvjpegDecodeParamsDestroy(params[i]));
    release(&outs[i]);
  }
  CHECK_NVJPEG(nvjpegJpegStateDestroy(state));
  return 0;
}

static int test_encode(nvjpegHandle_t handle) {
  // Decode the gradient to use as the encoder's device input.
  nvjpegJpegState_t decode_state = nullptr;
  CHECK_NVJPEG(nvjpegJpegStateCreate(handle, &decode_state));
  device_image source;
  if (allocate(&source, kImageA, true)) {
    return 1;
  }
  CHECK_NVJPEG(nvjpegDecode(handle, decode_state, kImageA.data, kImageA.length,
                            NVJPEG_OUTPUT_RGBI, &source.image, nullptr));
  CHECK_CUDA(cudaDeviceSynchronize());

  nvjpegEncoderState_t state = nullptr;
  nvjpegEncoderParams_t params = nullptr;
  CHECK_NVJPEG(nvjpegEncoderStateCreate(handle, &state, nullptr));
  CHECK_NVJPEG(nvjpegEncoderParamsCreate(handle, &params, nullptr));
  CHECK_NVJPEG(nvjpegEncoderParamsSetQuality(params, 95, nullptr));
  CHECK_NVJPEG(
      nvjpegEncoderParamsSetSamplingFactors(params, NVJPEG_CSS_444, nullptr));
  CHECK_NVJPEG(nvjpegEncoderParamsSetOptimizedHuffman(params, 1, nullptr));
  size_t max_length = 0;
  CHECK_NVJPEG(nvjpegEncodeGetBufferSize(handle, params, source.width,
                                         source.height, &max_length));
  EXPECT(max_length > 0);

  CHECK_NVJPEG(nvjpegEncodeImage(handle, state, params, &source.image,
                                 NVJPEG_INPUT_RGBI, source.width,
                                 source.height, nullptr));
  size_t length = 0;
  CHECK_NVJPEG(
      nvjpegEncodeRetrieveBitstream(handle, state, nullptr, &length, nullptr));
  EXPECT(length > 0 && length <= max_length);
  CHECK_CUDA(cudaDeviceSynchronize());

  // Asking again with a buffer too small reports the size and writes
  // nothing past what the caller has.
  std::vector<unsigned char> encoded(length + 16, 0xee);
  size_t short_length = 4;
  const nvjpegStatus_t short_status = nvjpegEncodeRetrieveBitstream(
      handle, state, encoded.data(), &short_length, nullptr);
  EXPECT(short_status != NVJPEG_STATUS_SUCCESS || short_length == length);
  EXPECT(encoded[4] == 0xee);

  size_t full_length = encoded.size();
  CHECK_NVJPEG(nvjpegEncodeRetrieveBitstream(handle, state, encoded.data(),
                                             &full_length, nullptr));
  CHECK_CUDA(cudaDeviceSynchronize());
  EXPECT(full_length == length);
  EXPECT(encoded[0] == 0xff && encoded[1] == 0xd8);
  EXPECT(encoded[length - 2] == 0xff && encoded[length - 1] == 0xd9);
  EXPECT(encoded[length] == 0xee);

  int components = 0;
  nvjpegChromaSubsampling_t subsampling = NVJPEG_CSS_UNKNOWN;
  int widths[NVJPEG_MAX_COMPONENT] = {};
  int heights[NVJPEG_MAX_COMPONENT] = {};
  CHECK_NVJPEG(nvjpegGetImageInfo(handle, encoded.data(), length, &components,
                                  &subsampling, widths, heights));
  EXPECT(components == 3 && subsampling == NVJPEG_CSS_444);
  EXPECT(widths[2] == 64 && heights[2] == 48);

  device_image round_trip;
  if (allocate(&round_trip, kImageA, false)) {
    return 1;
  }
  CHECK_NVJPEG(nvjpegDecode(handle, decode_state, encoded.data(), length,
                            NVJPEG_OUTPUT_RGB, &round_trip.image, nullptr));
  CHECK_CUDA(cudaDeviceSynchronize());
  if (check_pixels("encode round trip", round_trip)) {
    return 1;
  }

  // A full retrieval hands the bitstream over, so encode again and retrieve
  // the same bytes into device memory.
  unsigned char *device_bitstream = nullptr;
  CHECK_CUDA(cudaMalloc(&device_bitstream, max_length));
  CHECK_NVJPEG(nvjpegEncodeImage(handle, state, params, &source.image,
                                 NVJPEG_INPUT_RGBI, source.width,
                                 source.height, nullptr));
  size_t device_length = max_length;
  const nvjpegStatus_t device_status = nvjpegEncodeRetrieveBitstreamDevice(
      handle, state, device_bitstream, &device_length, nullptr);
  printf("  nvjpegEncodeRetrieveBitstreamDevice: %d (%zu bytes)\n",
         static_cast<int>(device_status), device_length);
  if (device_status == NVJPEG_STATUS_SUCCESS) {
    CHECK_CUDA(cudaDeviceSynchronize());
    EXPECT(device_length == length);
    std::vector<unsigned char> copied(device_length);
    CHECK_CUDA(cudaMemcpy(copied.data(), device_bitstream, device_length,
                          cudaMemcpyDeviceToHost));
    EXPECT(memcmp(copied.data(), encoded.data(), length) == 0);
  }
  cudaFree(device_bitstream);

  // The encoded bitstream's tables and parameters copy back into encoder
  // parameters through a parsed bitstream object.
  nvjpegJpegStream_t stream = nullptr;
  CHECK_NVJPEG(nvjpegJpegStreamCreate(handle, &stream));
  CHECK_NVJPEG(
      nvjpegJpegStreamParse(handle, encoded.data(), length, 0, 0, stream));
  CHECK_NVJPEG(nvjpegEncoderParamsCopyMetadata(state, params, stream, nullptr));
  CHECK_NVJPEG(
      nvjpegEncoderParamsCopyQuantizationTables(params, stream, nullptr));
  CHECK_NVJPEG(nvjpegJpegStreamDestroy(stream));

  release(&round_trip);
  release(&source);
  CHECK_NVJPEG(nvjpegEncoderParamsDestroy(params));
  CHECK_NVJPEG(nvjpegEncoderStateDestroy(state));
  CHECK_NVJPEG(nvjpegJpegStateDestroy(decode_state));
  return 0;
}

